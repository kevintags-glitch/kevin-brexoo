/**
 * Writes the data migration that loads the sample catalogue from config/samples.ts, so the website
 * mocks and the in-product sample data are the same records. Run: node scripts/generate-samples-sql.ts
 */
import { writeFileSync } from "node:fs";
import { SAMPLE_BUSINESSES, sampleEmail } from "../config/samples.ts";

const q = (s: string) => `'${s.replaceAll("'", "''")}'`;
const lines = ["-- Generated by scripts/generate-samples-sql.ts from config/samples.ts. Do not edit by hand.", ""];
for (const b of SAMPLE_BUSINESSES) {
  const data = { ...b, leads: b.leads.map((l) => ({ ...l, email: l.source === "manual" && !/\s/.test(l.name) ? null : sampleEmail(l.name) })) };
  lines.push(`insert into public.sample_businesses (key, data) values (${q(b.key)}, ${q(JSON.stringify(data))}::jsonb)`, `  on conflict (key) do update set data = excluded.data;`);
}
writeFileSync(new URL("../supabase/migrations/20261113001410_seed_samples.sql", import.meta.url), lines.join("\n") + "\n");
console.log(`wrote ${SAMPLE_BUSINESSES.length} sample businesses`);

// Local demo seed: one workspace per sample business, owned by demo+<key>@example.com
// (password "brexoo-demo"), with services, structured service areas and the sample data loaded.
import { areaLabel, areaSlug } from "../config/locations.ts";
const demo = [
  "-- Generated by scripts/generate-samples-sql.ts. Local development only: creates demo workspaces.",
  "-- Run: psql \"$DB_URL\" -f scripts/seed-demo.sql",
  "do $$",
  "declare uid uuid; org uuid;",
  "begin",
];
SAMPLE_BUSINESSES.forEach((b, i) => {
  const id = `00000000-0000-4000-8000-${String(i + 1).padStart(12, "0")}`;
  const slug = `demo-${b.key}`;
  demo.push(
    `  if not exists (select 1 from auth.users where id = '${id}') then`,
    `    insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, recovery_token, email_change_token_new, email_change)`,
    `    values ('00000000-0000-0000-0000-000000000000', '${id}', 'authenticated', 'authenticated', 'demo+${b.key}@example.com', extensions.crypt('brexoo-demo', extensions.gen_salt('bf')), now(), '{"provider":"email","providers":["email"]}', ${q(JSON.stringify({ full_name: "Jordan Avery" }))}, now(), now(), '', '', '', '');`,
    `    insert into auth.identities (id, user_id, provider_id, identity_data, provider, created_at, updated_at) values (gen_random_uuid(), '${id}', '${id}', jsonb_build_object('sub', '${id}', 'email', 'demo+${b.key}@example.com', 'email_verified', true), 'email', now(), now());`,
    `  end if;`,
    `  perform set_config('request.jwt.claims', json_build_object('sub', '${id}', 'role', 'authenticated')::text, true);`,
    `  select id into org from public.organizations where slug = '${slug}';`,
    `  if org is null then`,
    `    org := public.create_organization(${q(b.name)}, '${slug}', '${b.timezone}', '${b.country}', '${b.currency}');`,
    `    update public.organizations set phone = '000', contact_name = 'Jordan Avery', address_city = ${q(b.city)}, address_state = '${b.state}', address_county = ${b.county ? q(b.county) : "null"} where id = org;`,
    ...b.services.map((c) => `    insert into public.org_services (organization_id, category_code, template_version) values (org, '${c}', 1) on conflict do nothing;`),
    ...b.areas.map((a) => {
      const place = { country: b.country, state: b.state, ...a };
      return `    insert into public.service_areas (organization_id, label, country, state, county, city, suburb, postcode, slug) values (org, ${q(areaLabel(place))}, '${b.country}', '${b.state}', ${a.county ? q(a.county) : "null"}, ${q(a.city)}, ${a.suburb ? q(a.suburb) : "null"}, '${a.postcode}', '${areaSlug(place)}');`;
    }),
    `    perform public.load_sample_data(org, '${b.key}');`,
    `  end if;`,
  );
});
demo.push("end $$;");
writeFileSync(new URL("./seed-demo.sql", import.meta.url), demo.join("\n") + "\n");
console.log("wrote scripts/seed-demo.sql");
