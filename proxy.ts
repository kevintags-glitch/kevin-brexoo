import { createServerClient } from "@supabase/ssr";
import { NextResponse, type NextRequest } from "next/server";

/**
 * Refreshes the Supabase session cookie on every page request and keeps signed-out visitors out
 * of the app. Authorisation itself happens server-side (requireOrg) and in the database (RLS).
 */
const WORKSPACE_PATHS = /^\/(app|login|signup|verify|forgot-password|reset-password|invite|auth|p)(\/|$)/;

export async function proxy(request: NextRequest) {
  let response = NextResponse.next({ request });
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key = process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY;
  if (!url || !key) {
    // Website-only preview (no database connected): workspace and sign-in routes show a notice
    // instead of failing.
    if (WORKSPACE_PATHS.test(request.nextUrl.pathname)) {
      const to = request.nextUrl.clone();
      to.pathname = "/workspace-preview";
      to.search = "";
      return NextResponse.rewrite(to);
    }
    return response;
  }

  const supabase = createServerClient(url, key, {
    cookies: {
      getAll: () => request.cookies.getAll(),
      setAll: (list) => {
        for (const { name, value } of list) request.cookies.set(name, value);
        response = NextResponse.next({ request });
        for (const { name, value, options } of list) response.cookies.set(name, value, options);
      },
    },
  });

  const { data } = await supabase.auth.getClaims();
  const signedIn = Boolean(data?.claims?.sub);
  const path = request.nextUrl.pathname;

  if (!signedIn && path.startsWith("/app")) {
    const to = request.nextUrl.clone();
    to.pathname = "/login";
    to.search = `?next=${encodeURIComponent(path + request.nextUrl.search)}`;
    return NextResponse.redirect(to);
  }
  if (signedIn && (path === "/login" || path === "/signup")) {
    const to = request.nextUrl.clone();
    to.pathname = "/app";
    to.search = "";
    return NextResponse.redirect(to);
  }
  return response;
}

export const config = {
  matcher: ["/((?!_next/static|_next/image|favicon.ico|brand/|api/public|.*\\.(?:png|jpg|jpeg|svg|webp|ico|txt|xml)$).*)"],
};
